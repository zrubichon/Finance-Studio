export const frenchLabels:Record<string,string>=Object.fromEntries(pairs.split("\n").map(line=>line.split("|")));
export const termAliases:Record<string,string>={"ask offer":"ask","share stock":"share","share repurchase":"buyback","strike price":"strike","recovery":"recovery rate","strategic allocation":"strategic asset allocation","tactical allocation":"tactical asset allocation","moat":"economic moat","performance attribution":"attribution"};
export function cleanFrenchLabel(en:string,fr:string){
  if(frenchLabels[en])return frenchLabels[en];
  // Source vocabulary often already embeds an English gloss. Remove the repeated gloss.
  const parts=fr.split(/\s+\/\s+/).map(p=>p.trim()).filter(Boolean);
  const englishParts=en.split(/\s+\/\s+/).map(p=>p.toLowerCase());
  const kept=parts.filter(p=>!englishParts.includes(p.toLowerCase()));
  if(kept.length)return [...new Set(kept)].join(" / ");
  return fr.trim(); // International notation (alpha, delta, etc.) remains valid in both languages.
}
